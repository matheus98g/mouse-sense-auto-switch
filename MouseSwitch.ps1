# MouseSwitch.ps1 - automatically switches the pointer speed between Mouse and Trackpad
# Detects which device you are using (Raw Input) and adjusts the speed instantly.
# Left-click the tray icon = toggle manually (switches to Manual mode)
# Right-click = menu (Automatic/Manual, Mouse, Trackpad, Settings, Start with Windows,
#               Show last device, Exit)

# ===== Configuration =====
$DefaultMouseSpeed    = 12   # default mouse speed (1-20)
$DefaultTrackpadSpeed = 20   # default trackpad speed (1-20)
# Regex applied to the device name: if it matches, the device is treated as a MOUSE.
# "VID_" = USB devices (including wireless receivers), "VID&" = Bluetooth.
# Use "Show last device" in the menu to see the name and adjust if needed.
$MouseNameMatch = 'VID_|VID&'
# The current device must be idle this long (ms) before switching to the other one.
# Prevents flip-flopping when the mouse and the trackpad are used at the same time.
$SwitchHoldMs = 300
# =========================

$SettingsDir  = Join-Path $env:APPDATA 'MouseSwitch'
$SettingsFile = Join-Path $SettingsDir 'settings.json'
$RunKey       = 'HKCU:\Software\Microsoft\Windows\CurrentVersion\Run'
$RunValueName = 'MouseSwitch'
$StartupCmd   = "wscript.exe `"$(Join-Path $PSScriptRoot 'MouseSwitch.vbs')`""

Add-Type -AssemblyName System.Windows.Forms
