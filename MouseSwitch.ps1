# ===== Settings =====
function Limit-Speed($value, [int]$default) {
    $n = 0
    if (-not [int]::TryParse("$value", [ref]$n)) { return $default }
    return [Math]::Min(20, [Math]::Max(1, $n))
}

function Load-Settings {
    $script:MouseSpeed    = $DefaultMouseSpeed
    $script:TrackpadSpeed = $DefaultTrackpadSpeed
    $script:auto          = $true
    if (Test-Path $SettingsFile) {
        try {
            $s = Get-Content $SettingsFile -Raw | ConvertFrom-Json
            $script:MouseSpeed    = Limit-Speed $s.MouseSpeed    $DefaultMouseSpeed
            $script:TrackpadSpeed = Limit-Speed $s.TrackpadSpeed $DefaultTrackpadSpeed
            if ($null -ne $s.Auto) { $script:auto = [bool]$s.Auto }
        } catch { }
    }
}

function Save-Settings {
    try {
        if (-not (Test-Path $SettingsDir)) { New-Item -ItemType Directory -Path $SettingsDir -Force | Out-Null }
        [pscustomobject]@{
            MouseSpeed    = $script:MouseSpeed
            TrackpadSpeed = $script:TrackpadSpeed
            Auto          = $script:auto
        } | ConvertTo-Json | Set-Content -Path $SettingsFile -Encoding UTF8
    } catch { }
}

# ===== Start with Windows (per-user Run key, no admin needed) =====
function Get-Startup {
    $v = (Get-ItemProperty -Path $RunKey -Name $RunValueName -ErrorAction SilentlyContinue).$RunValueName
    return ($v -eq $StartupCmd)
}

function Set-Startup([bool]$on) {
    if ($on) {
        New-ItemProperty -Path $RunKey -Name $RunValueName -Value $StartupCmd -PropertyType String -Force | Out-Null
    } else {
        Remove-ItemProperty -Path $RunKey -Name $RunValueName -ErrorAction SilentlyContinue
    }
}

# ===== Icons: circle = automatic, square = manual =====
function New-TrayIcon([string]$text, [System.Drawing.Color]$color, [bool]$round) {
    $bmp = New-Object System.Drawing.Bitmap 32, 32
    $g = [System.Drawing.Graphics]::FromImage($bmp)
    $g.SmoothingMode = 'AntiAlias'
    $g.TextRenderingHint = 'AntiAliasGridFit'
    $g.Clear([System.Drawing.Color]::Transparent)
    $brush = New-Object System.Drawing.SolidBrush $color
    if ($round) { $g.FillEllipse($brush, 0, 0, 31, 31) } else { $g.FillRectangle($brush, 1, 1, 30, 30) }
    $font = New-Object System.Drawing.Font("Segoe UI", 14, [System.Drawing.FontStyle]::Bold, [System.Drawing.GraphicsUnit]::Pixel)
    $fmt = New-Object System.Drawing.StringFormat
    $fmt.Alignment = 'Center'; $fmt.LineAlignment = 'Center'
    $g.DrawString($text, $font, [System.Drawing.Brushes]::White, (New-Object System.Drawing.RectangleF 0, 1, 32, 32), $fmt)
    $g.Dispose()
    $hIcon = $bmp.GetHicon()
    $icon = [System.Drawing.Icon]::FromHandle($hIcon).Clone()
    [MouseSpeed]::DestroyIcon($hIcon) | Out-Null
    $bmp.Dispose()
    return $icon
}

$blue  = [System.Drawing.Color]::FromArgb(0, 120, 212)
$green = [System.Drawing.Color]::FromArgb(16, 137, 62)
$script:icons = @{}

function Build-Icons {
    $old = $script:icons
    $script:icons = @{
        'mouse-auto'      = New-TrayIcon "$($script:MouseSpeed)"    $blue  $true
        'trackpad-auto'   = New-TrayIcon "$($script:TrackpadSpeed)" $green $true
        'mouse-manual'    = New-TrayIcon "$($script:MouseSpeed)"    $blue  $false
        'trackpad-manual' = New-TrayIcon "$($script:TrackpadSpeed)" $green $false
    }
    # Swap the tray icon before disposing the old ones
    if ($tray -and $script:currentMode) { Update-Ui }
    foreach ($i in $old.Values) { $i.Dispose() }
}

# ===== Tray and menu =====
Load-Settings
$script:currentMode = ''

$tray = New-Object System.Windows.Forms.NotifyIcon
$menu = New-Object System.Windows.Forms.ContextMenuStrip
$itemAuto     = $menu.Items.Add("Mode: Automatic")
$itemManual   = $menu.Items.Add("Mode: Manual")
[void]$menu.Items.Add("-")
$itemMouse    = $menu.Items.Add("Mouse")
$itemTrackpad = $menu.Items.Add("Trackpad")
[void]$menu.Items.Add("-")
$itemSettings = $menu.Items.Add("Settings...")
$itemStartup  = $menu.Items.Add("Start with Windows")
$itemInfo     = $menu.Items.Add("Show last device")
[void]$menu.Items.Add("-")
$itemExit     = $menu.Items.Add("Exit (stop MouseSwitch)")
$tray.ContextMenuStrip = $menu
$menu.add_Opening({ $itemStartup.Checked = Get-Startup })

function Update-Ui {
    $suffix = if ($script:auto) { 'auto' } else { 'manual' }
    $tray.Icon = $script:icons["$($script:currentMode)-$suffix"]
    $label = if ($script:currentMode -eq 'trackpad') { "Trackpad - $($script:TrackpadSpeed)" } else { "Mouse - $($script:MouseSpeed)" }
    $tray.Text = if ($script:auto) { "$label (automatic)" } else { "$label (manual)" }
    $itemAuto.Checked     = $script:auto
    $itemManual.Checked   = -not $script:auto
    $itemMouse.Text       = "Mouse ($($script:MouseSpeed))"
    $itemTrackpad.Text    = "Trackpad ($($script:TrackpadSpeed))"
    $itemMouse.Checked    = ($script:currentMode -eq 'mouse')
    $itemTrackpad.Checked = ($script:currentMode -eq 'trackpad')
}

function Set-Mode([string]$mode, [switch]$Force) {
    if ($Force -or $mode -ne $script:currentMode) {
        if ($mode -eq 'trackpad') { [MouseSpeed]::Set($script:TrackpadSpeed) } else { [MouseSpeed]::Set($script:MouseSpeed) }
        $script:currentMode = $mode
    }
    Update-Ui
}

function Set-Auto([bool]$on) {
    $changed = ($script:auto -ne $on)
    $script:auto = $on
    if ($changed) { Save-Settings }
    if ($on) {
        $watcher.Reset()
        if ($watcher.LastKind) { Set-Mode $watcher.LastKind } else { Update-Ui }
    } else { Update-Ui }
}

function Show-SettingsDialog {
    $form = New-Object System.Windows.Forms.Form
    $form.Text = "MouseSwitch Settings"
    $form.FormBorderStyle = 'FixedDialog'
    $form.StartPosition = 'CenterScreen'
    $form.MaximizeBox = $false; $form.MinimizeBox = $false
    $form.TopMost = $true
    $form.ClientSize = New-Object System.Drawing.Size 300, 190
    $form.Font = New-Object System.Drawing.Font("Segoe UI", 9)

    $lblMouse = New-Object System.Windows.Forms.Label
    $lblMouse.Text = "Mouse speed (1-20):"; $lblMouse.SetBounds(15, 18, 160, 20)
    $numMouse = New-Object System.Windows.Forms.NumericUpDown
    $numMouse.Minimum = 1; $numMouse.Maximum = 20; $numMouse.Value = $script:MouseSpeed
    $numMouse.SetBounds(200, 15, 80, 23)

    $lblPad = New-Object System.Windows.Forms.Label
    $lblPad.Text = "Trackpad speed (1-20):"; $lblPad.SetBounds(15, 50, 160, 20)
    $numPad = New-Object System.Windows.Forms.NumericUpDown
    $numPad.Minimum = 1; $numPad.Maximum = 20; $numPad.Value = $script:TrackpadSpeed
    $numPad.SetBounds(200, 47, 80, 23)

    $chkAuto = New-Object System.Windows.Forms.CheckBox
    $chkAuto.Text = "Automatic switching"; $chkAuto.Checked = $script:auto
    $chkAuto.SetBounds(15, 82, 270, 22)

    $chkStartup = New-Object System.Windows.Forms.CheckBox
    $chkStartup.Text = "Start with Windows"; $chkStartup.Checked = (Get-Startup)
    $chkStartup.SetBounds(15, 108, 270, 22)

    $btnDefaults = New-Object System.Windows.Forms.Button
    $btnDefaults.Text = "Restore defaults"; $btnDefaults.SetBounds(15, 148, 110, 28)
    $btnDefaults.add_Click({
        $numMouse.Value = $DefaultMouseSpeed
        $numPad.Value = $DefaultTrackpadSpeed
        $chkAuto.Checked = $true
    })

    $btnSave = New-Object System.Windows.Forms.Button
    $btnSave.Text = "Save"; $btnSave.SetBounds(135, 148, 70, 28)
    $btnSave.DialogResult = 'OK'
    $btnCancel = New-Object System.Windows.Forms.Button
    $btnCancel.Text = "Cancel"; $btnCancel.SetBounds(210, 148, 70, 28)
    $btnCancel.DialogResult = 'Cancel'
    $form.AcceptButton = $btnSave
    $form.CancelButton = $btnCancel

    $form.Controls.AddRange(@($lblMouse, $numMouse, $lblPad, $numPad, $chkAuto, $chkStartup, $btnDefaults, $btnSave, $btnCancel))

    if ($form.ShowDialog() -eq 'OK') {
        $script:MouseSpeed    = [int]$numMouse.Value
        $script:TrackpadSpeed = [int]$numPad.Value
        $script:auto          = $chkAuto.Checked
        Save-Settings
        Build-Icons
        Set-Startup $chkStartup.Checked
        Set-Mode $script:currentMode -Force
        Set-Auto $chkAuto.Checked
    }
    $form.Dispose()
}

# Initial state from the current system speed
if ([MouseSpeed]::Get() -eq $script:TrackpadSpeed) { $script:currentMode = 'trackpad' } else { $script:currentMode = 'mouse' }
Build-Icons

$watcher = New-Object RawInputWatcher $MouseNameMatch
$watcher.HoldMs = $SwitchHoldMs
$watcher.add_DeviceChanged({
    param($kind)
    if ($script:auto) { Set-Mode $kind }
})

$tray.add_MouseClick({
    param($s, $e)
    if ($e.Button -eq [System.Windows.Forms.MouseButtons]::Left) {
        Set-Auto $false
        if ($script:currentMode -eq 'mouse') { Set-Mode 'trackpad' } else { Set-Mode 'mouse' }
    }
})
$itemAuto.add_Click({ Set-Auto $true })
$itemManual.add_Click({ Set-Auto $false })
$itemMouse.add_Click({ Set-Auto $false; Set-Mode 'mouse' })
$itemTrackpad.add_Click({ Set-Auto $false; Set-Mode 'trackpad' })
$itemSettings.add_Click({ Show-SettingsDialog })
$itemStartup.add_Click({ Set-Startup (-not (Get-Startup)) })
$itemInfo.add_Click({
    $kind = if ($watcher.LastKind -eq 'mouse') { 'MOUSE' } else { 'TRACKPAD' }
    [System.Windows.Forms.MessageBox]::Show(
        "Last device used (the one that clicked this menu):`n`n$($watcher.LastDeviceName)`n`nClassified as: $kind",
        "MouseSwitch") | Out-Null
})
$itemExit.add_Click({
    $tray.Visible = $false
    $tray.Dispose()
    foreach ($i in $script:icons.Values) { $i.Dispose() }
    $watcher.DestroyHandle()
    [System.Windows.Forms.Application]::Exit()
})

Update-Ui
