// MouseSwitch.cs - automatically switches the pointer speed between Mouse and Trackpad
// Detects which device you are using (Raw Input) and adjusts the speed instantly.
// Left-click the tray icon = toggle manually (switches to Manual mode)
// Right-click = menu (Automatic/Manual, Mouse, Trackpad, Settings, Start with Windows,
//               Show last device, Exit)
//
// Build with build.cmd (uses the csc.exe that ships with .NET Framework 4.x). C# 5 only.

